package com.example.SpringDataJpa.service;

import com.example.SpringDataJpa.Reposatiary.OrderRepositary;
import com.example.SpringDataJpa.Reposatiary.UserRepositary;
import com.example.SpringDataJpa.dto.OrderDto;
import com.example.SpringDataJpa.dto.CreateOrderDto;
import jakarta.transaction.Transactional;
import lombok.AllArgsConstructor;

import org.springframework.stereotype.Service;
import com.example.SpringDataJpa.entites.User;
import com.example.SpringDataJpa.entites.Order;
@Service

@AllArgsConstructor
public class OrderService {


















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































    private final OrderRepositary orderRepositary;
    private final UserRepositary userRepositary;
@Transactional
    public OrderDto createOrder(Long userId, CreateOrderDto createOrderdto) {
        User user = userRepositary.findById(userId).orElseThrow();
        Order order = new Order();
        order.setUser(user);
        order.setProductName(createOrderdto.getProductName());
        Order saveOrder = orderRepositary.save(order);
        return new OrderDto(saveOrder.getId(),saveOrder.getProductName(),saveOrder.getUser());

    }
}
